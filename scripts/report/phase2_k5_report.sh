#!/bin/sh
# scripts/report/phase2_k5_report.sh — regenerates results/docs/analysis/phase2_avx2_nt_analysis.txt.
#
#   sh scripts/report/phase2_k5_report.sh
#
# Every number in the output is printed by awk from a log or a CSV, or by the
# gate itself; none is typed in. It also re-runs `make audit` and
# `make audit-width`, so the report carries the gate's own verdict for the rungs
# that are present at generation time (Kernel 5 report item 1).
set -eu
cd "$(dirname "$0")/../.."

OUT=results/docs/analysis/phase2_avx2_nt_analysis.txt

{
printf 'KERNEL 5 (memcpy_avx2_nt) - ANALYZER OUTPUT, GATE PROOF AND PROBE EVIDENCE\n'
printf 'Generated by scripts/report/phase2_k5_report.sh; every number is printed by awk from a\n'
printf 'log or a CSV, or by the gate itself. Nothing here is typed in by hand.\n\n'

printf '================================================================================\n'
printf '1. THE MANDATORY GATE, AS OF THIS GENERATION\n'
printf '================================================================================\n'
printf 'make audit (scalar TUs must hold no vector instructions) and make audit-width\n'
printf '(every rung widest memory access must equal its declared width) both run below.\n'
printf 'scripts/measure/mo_measure.sh refuses to write a timing row if either fails, so the\n'
printf 'campaign logs that follow cannot exist unless the gate passed first.\n\n'
# No temporary files: capture into a variable so the command's own exit status is
# what gets reported. (Section 9 forbids evidence outside the repo, and a filter
# buffer in /tmp would be the same mistake in miniature.)
printf -- '--- make audit (rc and scalar-TU findings):\n'
audit_out=$(make -s audit 2>&1) && audit_rc=0 || audit_rc=$?
printf 'rc=%s\n' "$audit_rc"
printf '%s\n' "$audit_out" | grep -E 'SCALAR_SRCS' | sort -u | sed 's/^/  /'
printf '\n--- make audit-width (per rung, per target):\n'
width_out=$(sh scripts/verify/audit_width.sh 2>&1) && width_rc=0 || width_rc=$?
printf 'rc=%s\n' "$width_rc"
printf '%s\n' "$width_out" | grep -E 'declared|NO DECLARED|rung ' | sed 's/^/  /'
printf '\n--- the campaign logs own gate line, recorded before window 1:\n'
for t in znver2 znver3 v3; do
    grep -m1 '^# gate:' "results/live/phase2_avx2_nt_campaign_$t.windows.log" | sed "s/^/  $t: /"
done

printf '\n================================================================================\n'
printf '2. INSTRUMENT\n'
printf '================================================================================\n'
for t in znver2 znver3 v3; do
    head -2 "results/live/phase2_avx2_nt_campaign_$t.windows.log" | sed "s/^/  $t: /"
    printf '  %s: windows=%s rep_lines=%s migrated=%s cpu2=%s\n' "$t" \
        "$(grep -c '^# WINDOW' "results/live/phase2_avx2_nt_campaign_$t.windows.log")" \
        "$(grep -c '^REPS' "results/live/phase2_avx2_nt_campaign_$t.windows.log")" \
        "$(grep -c 'migrated=1' "results/live/phase2_avx2_nt_campaign_$t.windows.log")" \
        "$(grep -c 'cpu=2' "results/live/phase2_avx2_nt_campaign_$t.windows.log")"
done

printf '\n================================================================================\n'
printf '3. KERNEL 5 vs KERNEL 4 (memcpy_avx2_nt vs the cached memcpy_avx2), same windows\n'
printf '================================================================================\n'
for t in znver2 znver3 v3; do
    printf '\n################ %s ################\n\n' "$t"
    sh scripts/analyze/mo_analyze.sh "results/live/phase2_avx2_nt_campaign_$t.windows.log" avx2_nt avx2 "$t"
done

printf '\n================================================================================\n'
printf '4. DID THE KERNEL ACTUALLY USE NON-TEMPORAL STORES? (verify cannot see this)\n'
printf '================================================================================\n'
printf 'Census of the committed rung object per target. _mm256_stream_si256 compiles to\n'
printf 'vmovntps on this clang, not vmovntdq, which is why the first grep for vmovntdq\n'
printf 'found nothing and looked like a missing NT path. The saved codegen diffs show\n'
printf 'only CHANGED lines, so they cannot serve as a census; this can.\n\n'
for t in znver2 znver3 v3; do
    o="build/$t/src/memcpy_avx2_nt.o"
    printf '  %-7s vmovntps=%s sfence=%s vmovups(32B cached)=%s  instructions=%s obj_bytes=%s\n' "$t" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c vmovntps)" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c sfence)" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c 'vmovups.*ymm')" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -cE '^[[:space:]]*[0-9a-f]+:')" \
        "$(wc -c < "$o")"
done

printf '\n================================================================================\n'
printf '5. NT THRESHOLD PROBE (diagnostic): where does NT start winning?\n'
printf '================================================================================\n'
printf 'scripts/measure/nt_threshold_probe.sh forces the threshold to 64 B so NT applies to every\n'
printf 'main-path size, and sweeps against the cached rung in the same process. This is an\n'
printf 'INFERENCE from the throughput inflection, not a measurement of a cache boundary:\n'
printf 'this box exposes no L3/LLC events (MEASUREMENT_PROTOCOL.md section 5).\n'
for t in znver2 znver3 v3; do
    printf '\n#### %s\n\n' "$t"
    printf '| size | cached ns | NT ns | delta | cached GB/s | NT GB/s | NT wins? |\n|--:|--:|--:|--:|--:|--:|:--|\n'
    awk '
        /^REPS / {
            impl=$2; op=$3; n=0; mn=-1
            for (i=4;i<=NF;i++) { split($i,kv,"="); k=kv[1]; v=kv[2]+0
                if (k=="n") n=v; else if (k=="min_ns") mn=v }
            if (op!="memcpy" || n==0 || mn<=0) next
            key=impl"|"n
            if (!((key) in best) || mn<best[key]) best[key]=mn
            if (n>maxn) maxn=n
        }
        END {
            w=0
            for (i=1;i<=maxn;i++) if ((("avx2|" i) in best) && (("avx2_nt|" i) in best)) {
                c=best["avx2|" i]; nt=best["avx2_nt|" i]; d=100*(c-nt)/c
                printf "| %d | %.1f | %.1f | %+.2f%% | %.2f | %.2f | %s |\n", i, c, nt, d, i/c, i/nt, (d>0)?"YES":"no"
                if (d>0 && w==0) w=i
            }
            printf "\n  first size where NT wins: %s\n", (w==0) ? "NONE (NT loses at every size)" : w
        }' "results/live/phase2_avx2_nt_threshold_probe_$t.log"
done
printf '\nThe same logs carry the unaligned-handling cost: the harness --align2d sweep at\n'
printf '1 MiB, DT offsets that are multiples of 32 (the NT body runs directly) against the\n'
printf 'rest (a cached lead of up to 31 B runs first).\n\n'
for t in znver2 znver3 v3; do
    awk -F, -v T="$t" 'NF==9 && $4+0 == 1048576 && $1=="avx2_nt" {
        dof=$6+0; ns=$7+0; a=(dof%32==0)
        if (a) { na++; sa+=ns; if (na==1||ns<ma) ma=ns } else { nu++; su+=ns; if (nu==1||ns<mu) mu=ns } }
      END { printf "  %-7s aligned n=%2d min=%.0f mean=%.0f ns | unaligned n=%2d min=%.0f mean=%.0f ns | cost(min)=%+.2f%% cost(mean)=%+.2f%%\n", \
        T, na, ma, sa/na, nu, mu, su/nu, 100*(mu-ma)/ma, 100*(su/nu-sa/na)/(sa/na) }' \
        "results/live/phase2_avx2_nt_threshold_probe_$t.log"
done

printf '\n================================================================================\n'
printf '6. CROSS-TARGET CODEGEN CAVEAT FOR THIS RUNG\n'
printf '================================================================================\n'
printf 'Unlike Kernel 4 (where znver2 and znver3 produced identical AVX2 streams), this\n'
printf 'rung compiles differently per target, so its cross-target rows are not the same\n'
printf 'binary and must not be read as a hardware comparison. Each saved diff carries\n'
printf 'its own verdict and mnemonic-multiset lines; they are printed here.\n'
for f in results/docs/codegen/codegen_diff_avx2_nt_*.diff; do
    printf '  %s\n' "$(basename "$f")"
    grep -E '^# (verdict|mnemonic multiset):' "$f" | sed 's/^/    /'
done

printf '\n================================================================================\n'
printf 'END OF KERNEL 5 ANALYSIS\n'
printf '================================================================================\n'
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
