#!/bin/sh
# scripts/phase2_hybrid_report.sh — regenerates results/phase2_hybrid_analysis.txt
#
#   sh scripts/phase2_hybrid_report.sh
#
# Every number printed here comes from a campaign log, a frozen CSV, an object
# file, or the gate itself. Nothing is typed in. The script re-runs `make audit`,
# `make audit-width` and `make routecheck` so the report carries the gate's own
# verdict for the rungs present at generation time.
set -eu
cd "$(dirname "$0")/.."

OUT=results/phase2_hybrid_analysis.txt
LOGS=results/phase2_hybrid_campaign
PROV=results/phase2_hybrid_routing.txt
LADDER="naive word sse2 avx2 avx2_nt asm"
TARGETS="znver2 znver3 v3"

# routed <target> <size> - the rung the generated table sends that size to, read
# out of the provenance's emitted-table (section 5) rows and then applying the
# audited lookup rule to it: the LAST measured point <= n, clamped to the smallest
# point below n=16 and to the largest point above the top. So a measured size
# answers with its own winner, and an in-between size (100, 1000, 20000, 300000
# below) answers with the conservative lower point's winner - the same rule
# tools/route_check.c re-derives from the built object for 0 .. 8 MiB.
#
# Two parsing traps this avoids: the `### <target>` marker contains no `|`, so the
# target must be read from $0 (reading it from $2 matches nothing); and the pipe
# fields carry padding spaces, so they must be stripped before a numeric compare.
routed() {
    awk -v T="$1" -v N="$2" -F'|' '
        /^### / { cur = $0; sub(/^### +/, "", cur); gsub(/[ \t]*$/, "", cur); next }
        cur == T && $4 ~ /winner at/ {
            c0 = $1; b = $2; r = $3
            gsub(/[ \t]/, "", c0); gsub(/[ \t]/, "", b); gsub(/[ \t]/, "", r)
            if (c0 !~ /^[0-9]+$/) next
            nseen++
            if (nseen == 1) { first = r }
            if ((b + 0) <= (N + 0)) { last = r }
        }
        END { print (last != "") ? last : first }' "$PROV"
}

{
printf 'PHASE 2.5 HYBRID DISPATCHER - ANALYZER OUTPUT, GATE PROOF AND ROUTING EVIDENCE\n'
printf 'Generated by scripts/phase2_hybrid_report.sh. Every number is printed by awk from a\n'
printf 'campaign log, a frozen CSV or an object, or by the gate itself.\n\n'

printf '================================================================================\n'
printf '1. THE MANDATORY GATE\n'
printf '================================================================================\n'
audit_out=$(make -s audit 2>&1) && audit_rc=0 || audit_rc=$?
printf 'make audit        rc=%s (scalar TUs must hold no vector instruction)\n' "$audit_rc"
printf '%s\n' "$audit_out" | grep -E 'SCALAR_SRCS' | sort -u | sed 's/^/  /'
width_out=$(sh scripts/audit_width.sh 2>&1) && width_rc=0 || width_rc=$?
printf 'make audit-width  rc=%s\n' "$width_rc"
printf '%s\n' "$width_out" | grep -E '^--- target|DISPATCHER|audit_width: ' | sed 's/^/  /'
printf 'make routecheck   ' ; route_out=$(sh scripts/hybrid_route_check.sh 2>&1) && route_rc=0 || route_rc=$?
printf 'rc=%s\n' "$route_rc"
printf '%s\n' "$route_out" | grep -E 'check 1|check 2|check 3|route_check:|hybrid_route_check:|provenance' | sed 's/^/  /'
printf '\nthe campaign logs own gate line, recorded before window 1:\n'
for t in $TARGETS; do
    grep -m1 '^# gate:' "${LOGS}_$t.windows.log" | sed "s/^/  $t: /"
done
printf '\nscripts/mo_measure.sh refuses to write a timing row unless make gate passes, so the\n'
printf 'logs below cannot exist unless the gate passed first.\n'

printf '\n================================================================================\n'
printf '2. INSTRUMENT\n'
printf '================================================================================\n'
for t in $TARGETS; do
    head -2 "${LOGS}_$t.windows.log" | sed "s/^/  $t: /"
    printf '  %s: windows=%s rep_lines=%s migrated=%s cpu2=%s\n' "$t" \
        "$(grep -c '^# WINDOW' "${LOGS}_$t.windows.log")" \
        "$(grep -c '^REPS' "${LOGS}_$t.windows.log")" \
        "$(grep -c 'migrated=1' "${LOGS}_$t.windows.log")" \
        "$(grep -c 'cpu=2' "${LOGS}_$t.windows.log")"
done
printf '\n  Note on the extra rep lines for glibc and ref_scalar: those are the only two\n'
printf '  requested impls that have a memset side, so the harness also runs their memset\n'
printf '  cases. The analyzer filters op=memcpy, so no comparison below uses them.\n'

printf '\n================================================================================\n'
printf '3. THE ROUTING TABLE AS COMPILED (src/routing_table.h, generated)\n'
printf '================================================================================\n'
printf 'Full provenance: results/phase2_hybrid_routing.txt\n\n'
for t in $TARGETS; do
    printf '### %s\n\n' "$t"
    printf 'class | bytes | rung\n--:|--:|:--\n'
    awk -v T="$t" -F'|' '
        /^### / { cur = $0; sub(/^### +/, "", cur); gsub(/[ \t]*$/, "", cur); next }
        cur == T && $4 ~ /winner at/ {
            c0 = $1; b = $2; r = $3
            gsub(/[ \t]/, "", c0); gsub(/[ \t]/, "", b); gsub(/[ \t]/, "", r)
            if (c0 ~ /^[0-9]+$/) printf "%s | %s B | %s\n", c0, b, r
        }' "$PROV"
    printf '\n'
done

printf '================================================================================\n'
printf '4. STANDING REPORT - hybrid vs the strongest single rung and vs glibc, same windows\n'
printf '   (mo_analyze.sh with PREV=asm)\n'
printf '================================================================================\n'
printf 'The single-kernel denominator here is asm, chosen because the routing provenance\n'
printf 'counts it the most-won rung on this silicon:\n'
awk '/^  target +naive/ { h=1 } h && /^$/ { exit } h { print }' "$PROV" | sed 's/^/  /'
printf '\nSection 5 then replaces it with the per-size best rung, which is the proper\n'
printf 'denominator for a dispatcher: asm is the strongest rung but is not the best rung at\n'
printf 'every size, and per-size best is the floor the dispatcher is trying to reach.\n'
for t in $TARGETS; do
    printf '\n################ %s ################\n\n' "$t"
    sh scripts/mo_analyze.sh "${LOGS}_$t.windows.log" hybrid asm "$t"
done

printf '\n================================================================================\n'
printf '5. THE HYPOTHESIS TEST: hybrid vs THE BEST SINGLE RUNG AT EACH SIZE\n'
printf '================================================================================\n'
printf 'Per size: which rung the generated table routes that size to, the fastest of the\n'
printf 'six ladder rungs in THESE campaign windows (the floor a dispatcher can reach), and\n'
printf 'the hybrid. "hybrid vs best" positive = the hybrid is SLOWER than the best single\n'
printf 'rung, which is the dispatcher reading its own table and jumping: that is what the\n'
printf 'hybrid must pay. Negative = the hybrid faster than every single rung, which cannot\n'
printf 'be a real effect (it IS one of them plus a lookup) and is instrument noise.\n'
for t in $TARGETS; do
    printf '\n### %s\n\n' "$t"
    printf '| size | routed rung | rung | best min_ns | hybrid min_ns | hybrid vs best | glibc min_ns | hybrid vs glibc |\n'
    printf '|--:|:--|:--|--:|--:|--:|--:|--:|\n'
    for n in 16 32 64 100 128 256 512 1000 1024 4096 16384 20000 65536 262144 300000 1048576 4194304; do
        awk -v T="$t" -v N="$n" -v L="$LADDER" -v ROUTED="$(routed "$t" "$n")" '
            $1 == "REPS" {
                impl = $2; op = $3; nn = 0; mn = -1; mig = 0
                for (i = 4; i <= NF; i++) {
                    split($i, kv, "="); k = kv[1]; v = kv[2] + 0
                    if (k == "n") nn = v; else if (k == "min_ns") mn = v; else if (k == "migrated") mig = v
                }
                if (op != "memcpy" || nn != N || mn <= 0 || mig == 1) next
                if (!((impl) in best) || mn < best[impl]) best[impl] = mn
            }
            END {
                nl = split(L, R, " ")
                bw = ""; bv = 0
                for (i = 1; i <= nl; i++) if ((R[i] in best) && (bv == 0 || best[R[i]] < bv)) { bv = best[R[i]]; bw = R[i] }
                h = (("hybrid" in best) ? best["hybrid"] : 0)
                g = (("glibc" in best) ? best["glibc"] : 0)
                printf "| %s | %s | %s | %.1f | %.1f | %+.2f%% | %.1f | %+.2f%% |\n", N, ROUTED, bw, bv, h,
                       (bv > 0 ? 100 * (h - bv) / bv : 0), g, (g > 0 ? 100 * (g - h) / g : 0)
            }' "${LOGS}_$t.windows.log"
    done
done

printf '\n================================================================================\n'
printf '5b. PER SIZE: THE ROUTED RUNG, AND THE SANCTIONED VERDICT vs glibc\n'
printf '================================================================================\n'
printf 'Read from the frozen CSVs (which section 4 wrote), so the verdicts are the claim\n'
printf "model's own and not a re-derivation here. tier A/B decides the floor: A = max(1.5%%, band),\n"
printf 'B = 25%% flat. "measured" is a cell with no claim in it either way.\n'
for t in $TARGETS; do
    printf '\n### %s\n\n' "$t"
    printf '| size | tier | routed rung | hybrid min_ns | glibc min_ns | d vs glibc | rule3 | band | TIER VERDICT vs glibc |\n'
    printf '|--:|:--|:--|--:|--:|--:|:--|:--|:--|\n'
    # size list from the CSV itself (never typed), rung per size from the audited rule
    SZMAP="build/$t/hybrid_route_by_size.txt"
    mkdir -p "build/$t"
    awk -F, 'NR > 1 && !seen[$4]++ { print $4 }' "results/phase2_hybrid_$t.csv" | sort -n | \
        while read -r n; do printf '%s,%s\n' "$n" "$(routed "$t" "$n")"; done > "$SZMAP"
    awk -F, '
        FNR == NR { r[$1] = $2; next }
        NR == 1 { next }
        {
            if ($1 == "hybrid") { hmin[$4] = $6; tier[$4] = $19; d[$4] = $10; r3[$4] = $12; bd[$4] = $14; tv[$4] = $22 }
            if ($1 == "glibc")  { gmin[$4] = $6 }
            if (!($4 in seen)) { seen[$4] = 1; sz[++ns] = $4 }
        }
        END {
            for (i = 1; i <= ns; i++) for (j = i + 1; j <= ns; j++) if (sz[j] + 0 < sz[i] + 0) { t2 = sz[i]; sz[i] = sz[j]; sz[j] = t2 }
            for (i = 1; i <= ns; i++) {
                n = sz[i]
                if (!((n) in hmin)) continue
                printf "| %s | %s | %s | %.1f | %.1f | %+.2f%% | %s | %s | %s |\n", \
                    n, tier[n], r[n], hmin[n], gmin[n], d[n], r3[n], bd[n], tv[n]
            }
        }' "$SZMAP" "results/phase2_hybrid_$t.csv"
done

printf '\n================================================================================\n'
printf '6. WHAT ONE KERNEL WOULD COST vs WHAT THE DISPATCHER COSTS\n'
printf '================================================================================\n'
printf 'For every size in the hybrid campaign: the per-size best rung value (the floor a\n'
printf 'dispatcher can reach) and, for each single rung, its penalty against that floor.\n'
printf 'This is the measurement behind "no single kernel wins everywhere", and it is what\n'
printf 'decides whether the hybrid is worth its lookup.\n'
for t in $TARGETS; do
    printf '\n### %s\n\n' "$t"
    printf '| rung | sizes won | median penalty vs best | worst penalty (at size) |\n|:--|--:|--:|:--|\n'
    awk -v L="$LADDER" '
        $1 == "REPS" {
            impl = $2; op = $3; nn = 0; mn = -1; mig = 0
            for (i = 4; i <= NF; i++) {
                split($i, kv, "="); k = kv[1]; v = kv[2] + 0
                if (k == "n") nn = v; else if (k == "min_ns") mn = v; else if (k == "migrated") mig = v
            }
            if (op != "memcpy" || mn <= 0 || mig == 1) next
            if (!((impl "|" nn) in best) || mn < best[impl "|" nn]) best[impl "|" nn] = mn
            size[nn] = 1; impls[impl] = 1
        }
        END {
            nl = split(L, R, " ")
            for (n in size) {
                bv = 0
                for (i = 1; i <= nl; i++) if ((R[i] "|" n) in best && (bv == 0 || best[R[i] "|" n] < bv)) bv = best[R[i] "|" n]
                for (i = 1; i <= nl; i++) if ((R[i] "|" n) in best) {
                    d = 100 * (best[R[i] "|" n] - bv) / bv
                    key = R[i]
                    cnt[key]++; pen[key, cnt[key]] = d
                    if (d > worst[key]) { worst[key] = d; wsize[key] = n }
                    if (d <= 0.0001) won[key]++
                }
                if (("hybrid|" n) in best && bv > 0) {
                    d = 100 * (best["hybrid|" n] - bv) / bv
                    cnt["hybrid"]++; pen["hybrid", cnt["hybrid"]] = d
                    if (d > worst["hybrid"]) { worst["hybrid"] = d; wsize["hybrid"] = n }
                    if (d <= 0.0001) won["hybrid"]++
                }
            }
            nm = split(L " hybrid", ALL, " ")
            for (i = 1; i <= nm; i++) {
                r = ALL[i]
                m = cnt[r]; if (m == 0) continue
                for (j = 1; j <= m; j++) for (k = j + 1; k <= m; k++) if (pen[r, k] < pen[r, j]) { t2 = pen[r, j]; pen[r, j] = pen[r, k]; pen[r, k] = t2 }
                med = (m % 2) ? pen[r, (m + 1) / 2] : (pen[r, m / 2] + pen[r, m / 2 + 1]) / 2
                printf "| %s | %d/%d | +%.2f%% | +%.2f%% (%s B) |\n", r, won[r] + 0, m, med, worst[r], wsize[r]
            }
        }' "${LOGS}_$t.windows.log"
done

printf '\n================================================================================\n'
printf '7. TWO-TIER CLAIM MODEL SUMMARY (the sanctioned verdicts, from the CSVs above)\n'
printf '================================================================================\n'
printf 'Both denominators are shown per target: asm (the strongest single rung, so a WIN\n'
printf 'here is what a dispatcher is FOR) and glibc (the baseline the project is chasing).\n'
printf 'WIN/LOSS are the tier verdicts from results/MEASUREMENT_PROTOCOL.md section 3c: in\n'
printf 'a Tier A cell the floor is max(1.5%%, band), in a Tier B cell it is 25%%. A cell in\n'
printf 'Tier B is printed "measured" whatever its raw delta - that is NOT a tie claim, it is\n'
printf 'a cell this instrument cannot resolve, and the tier counts are printed so the reader\n'
printf 'can see how much of each row that covers.\n'
for t in $TARGETS; do
    printf '\n### %s\n\n' "$t"
    awk -F, '
        NR == 1 { next }
        $1 != "hybrid" { next }
        {
            cells++
            tier[$19]++
            vp[$21]++; vg[$22]++
            bv[$14]++
            if ($21 == "WIN")  pw = pw " " $4
            if ($21 == "LOSS") pl = pl " " $4
            if ($22 == "WIN")  gw = gw " " $4
            if ($22 == "LOSS") gl = gl " " $4
        }
        END {
            printf "  cells=%d   tier A=%d  tier B=%d\n", cells, tier["A"], tier["B"]
            if (!cells) { print "  (no hybrid rows in this CSV - run section 4)"; exit }
            printf "  vs asm:   WIN=%d  measured=%d  LOSS=%d\n", vp["WIN"], vp["measured"], vp["LOSS"]
            printf "    tier WIN at:%s\n", (pw != "") ? pw : " (none)"
            printf "    tier LOSS at:%s\n", (pl != "") ? pl : " (none)"
            printf "  vs glibc: WIN=%d  measured=%d  LOSS=%d      (band verdicts: WIN=%d within-noise=%d LOSS=%d)\n", \
                   vg["WIN"], vg["measured"], vg["LOSS"], bv["WIN"], bv["within-noise"], bv["LOSS"]
            printf "    tier WIN at:%s\n", (gw != "") ? gw : " (none)"
            printf "    tier LOSS at:%s\n", (gl != "") ? gl : " (none)"
        }' "results/phase2_hybrid_$t.csv"
done

printf '\n================================================================================\n'
printf 'END OF PHASE 2.5 HYBRID ANALYSIS\n'
printf '================================================================================\n'
} > "$OUT"
echo "wrote $OUT ($(grep -c '' "$OUT") lines)"
