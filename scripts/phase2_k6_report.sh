#!/bin/sh
# scripts/phase2_k6_report.sh — regenerates results/phase2_asm_analysis.txt.
#
#   sh scripts/phase2_k6_report.sh
#
# Every number in the output is printed by awk from a log, a CSV or an object
# file, or by the gate itself; none is typed in. It also re-runs `make audit` and
# `make audit-width`, so the report carries the gate's own verdict for every rung
# present at generation time (Kernel 6 report item 1).
set -eu
cd "$(dirname "$0")/.."

OUT=results/phase2_asm_analysis.txt

{
printf 'KERNEL 6 (memcpy_asm, hand-written AVX2 assembly) - ANALYZER OUTPUT,\n'
printf 'GATE PROOF AND CODEGEN EVIDENCE\n'
printf 'Generated by scripts/phase2_k6_report.sh; every number is printed by awk from a\n'
printf 'log, a CSV or an object, or by the gate itself. Nothing here is typed in.\n\n'

printf '================================================================================\n'
printf '1. THE MANDATORY GATE, AS OF THIS GENERATION\n'
printf '================================================================================\n'
printf 'make audit (scalar TUs must hold no vector instructions) and make audit-width\n'
printf '(every rung widest memory access must equal its declared width) both run below.\n'
printf 'scripts/mo_measure.sh refuses to write a timing row if either fails, so the\n'
printf 'campaign logs that follow cannot exist unless the gate passed first.\n\n'
printf -- '--- make audit (rc and scalar-TU findings):\n'
audit_out=$(make -s audit 2>&1) && audit_rc=0 || audit_rc=$?
printf 'rc=%s\n' "$audit_rc"
printf '%s\n' "$audit_out" | grep -E 'SCALAR_SRCS' | sort -u | sed 's/^/  /'
printf '\n--- make audit-width (per rung, per target):\n'
width_out=$(sh scripts/audit_width.sh 2>&1) && width_rc=0 || width_rc=$?
printf 'rc=%s\n' "$width_rc"
printf '%s\n' "$width_out" | grep -E 'declared|NO DECLARED|rung ' | sed 's/^/  /'
printf '\n--- the campaign logs own gate line, recorded before window 1:\n'
for t in znver2 znver3 v3; do
    grep -m1 '^# gate:' "results/phase2_asm_campaign_$t.windows.log" | sed "s/^/  $t: /"
done

printf '\n================================================================================\n'
printf '2. INSTRUMENT\n'
printf '================================================================================\n'
for t in znver2 znver3 v3; do
    head -2 "results/phase2_asm_campaign_$t.windows.log" | sed "s/^/  $t: /"
    printf '  %s: windows=%s rep_lines=%s migrated=%s cpu2=%s\n' "$t" \
        "$(grep -c '^# WINDOW' "results/phase2_asm_campaign_$t.windows.log")" \
        "$(grep -c '^REPS' "results/phase2_asm_campaign_$t.windows.log")" \
        "$(grep -c 'migrated=1' "results/phase2_asm_campaign_$t.windows.log")" \
        "$(grep -c 'cpu=2' "results/phase2_asm_campaign_$t.windows.log")"
done

printf '\n================================================================================\n'
printf '3. KERNEL 6 vs KERNEL 4 (memcpy_asm vs the C memcpy_avx2), min_of_mins, same windows\n'
printf '   and vs glibc. Tiers, both rule-3/band verdicts and the tier verdict per size.\n'
printf '================================================================================\n'
for t in znver2 znver3 v3; do
    printf '\n################ %s ################\n\n' "$t"
    sh scripts/mo_analyze.sh "results/phase2_asm_campaign_$t.windows.log" asm avx2 "$t"
done

printf '\n================================================================================\n'
printf '4. WHAT THE ASSEMBLED RUNGS ACTUALLY CONTAIN (verify cannot see any of this)\n'
printf '================================================================================\n'
printf 'Per target: the two loops, the prefetch, the AVX-return state clearing and the\n'
printf 'object identity ACROSS targets. Kernel 5 compiled to a different instruction set\n'
printf 'per target; a hand-written stream cannot, and this is where that is checked.\n\n'
for t in znver2 znver3 v3; do
    o="build/$t/src/memcpy_asm.o"
    printf '  %-7s instructions=%-4s obj_bytes=%-5s vmovdqa=%-3s vmovdqu=%-3s vmovdqu(xmm)=%-3s prefetcht0=%-3s vzeroupper=%s\n' "$t" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -cE '^[[:space:]]*[0-9a-f]+:')" \
        "$(wc -c < "$o")" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c 'vmovdqa')" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c 'vmovdqu.*ymm')" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c 'vmovdqu.*xmm')" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c 'prefetcht0')" \
        "$(objdump -d --no-show-raw-insn "$o" | grep -c 'vzeroupper')"
done
printf '\n  object identity across the three targets (md5 of build/<t>/src/memcpy_asm.o):\n'
md5sum build/znver2/src/memcpy_asm.o build/znver3/src/memcpy_asm.o build/v3/src/memcpy_asm.o | sed 's/^/    /'
nuniq=$(md5sum build/*/src/memcpy_asm.o | awk '{print $1}' | sort -u | wc -l)
printf '    distinct hashes: %s (1 means the hand-written stream is target-independent)\n' "$nuniq"

printf '\n================================================================================\n'
printf '5. ASM vs THE C COMPILER: the saved per-target codegen diffs (report item 8)\n'
printf '================================================================================\n'
printf 'memcpy_asm (hand-written) against memcpy_avx2 (what clang -O3 -march=<t> produced\n'
printf 'for Kernel 4). Each file states the instruction counts, the verdict and the\n'
printf 'mnemonic-multiset verdict; the headers are reproduced here.\n'
for t in znver2 znver3 v3; do
    f="results/codegen_diff_asm_vs_avx2_c_$t.diff"
    if [ -f "$f" ]; then
        printf '\n  --- %s\n' "$(basename "$f")"
        grep -E '^# (memcpy_asm|memcpy_avx2|verdict|mnemonic multiset)' "$f" | sed 's/^/    /'
    else
        printf '\n  --- MISSING %s (run sh scripts/codegen_diff_asm_vs_c.sh)\n' "$f"
    fi
done

printf '\n================================================================================\n'
printf '6. TARGET-VS-TARGET FOR THE ASM RUNG (is the hand-written stream -march-sensitive?)\n'
printf '================================================================================\n'
for f in results/codegen_diff_asm_znver2_vs_znver3.diff \
         results/codegen_diff_asm_znver2_vs_v3.diff \
         results/codegen_diff_asm_znver3_vs_v3.diff; do
    if [ -f "$f" ]; then
        printf '  %s\n' "$(basename "$f")"
        grep -E '^# (verdict|mnemonic multiset):' "$f" | sed 's/^/    /'
    else
        printf '  MISSING %s\n' "$f"
    fi
done

printf '\n================================================================================\n'
printf 'END OF KERNEL 6 ANALYSIS\n'
printf '================================================================================\n'
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
