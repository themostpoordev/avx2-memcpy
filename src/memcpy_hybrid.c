/* src/memcpy_hybrid.c — Phase 2.5: the hybrid dispatcher rung.
 *
 * IDEA
 *   Six rungs exist and the measurements say no single one of them is fastest
 *   at every size on any target (results/phase2_hybrid_routing.txt section 6:
 *   sse2 wins 3 sizes, avx2 3-5, avx2_nt 0-1 and asm 5-6 of the 13 measured
 *   points, per target). glibc wins the small band because it dispatches to a
 *   different routine per size; this rung tries the same strategy with OUR
 *   rungs, and nothing else.
 *
 * THIS FILE CONTAINS NO COPY LOOP AND NO DATA MOVEMENT OF ITS OWN
 *   It classifies the size, indexes a generated table, and tail-calls the rung
 *   that won that class. `make audit-width` enforces that structurally: for a
 *   dispatcher TU it requires (a) no vector data movement of its own, (b) every
 *   undefined symbol to be a rung entry point that is itself width-gated, and
 *   (c) the declared width to equal the maximum declared width of the rungs it
 *   routes to (256 here). A comment claiming "it just dispatches" would prove
 *   nothing; the gate reads it out of the object.
 *
 * THE TABLE IS DATA FROM MEASUREMENT, NOT A CHOICE
 *   src/routing_table.h is generated by scripts/gen_routing_table.sh from
 *   min_of_mins measured in one window set (the Kernel 6 campaign measured
 *   every ladder rung plus glibc in the same 9 windows x 5 reps on cpu 2). The
 *   generator prints the winner, the runner-up and the margin per cell, the
 *   cells whose margin is inside the null band, and every cell where the frozen
 *   committed CSVs would have chosen differently. Regenerating is one command.
 *
 * ROUTING RULES (as requested for Phase 2.5, section 3)
 *   * classes are the 13 measured sizes, 16 B .. 4 MiB;
 *   * a size between two measured points uses the lower point's winner;
 *   * below 16 B uses the 16 B winner; above 4 MiB uses the 4 MiB winner.
 *   16 MiB / 64 MiB / 256 MiB are in the request's size list but were NEVER
 *   measured in Phase 2 (no campaign ran them), so they are not classes: they
 *   fall under the "above the top point" rule and route to the 4 MiB winner.
 *   Inventing a winner for them would be hand-picking with extra steps.
 *
 * WHAT IS DELIBERATELY NOT ROUTED TO
 *   * glibc: it is the baseline this project is trying to beat. Calling it here
 *     would make the rung a wrapper and the measurement meaningless.
 *   * ref_scalar: the verification reference, not a rung.
 *   * avx2_pf2 / avx2_pf4: Kernel 4 prefetch-distance variants, not ladder
 *     rungs, and no single campaign measured them together with the asm rung —
 *     routing to them would require the cross-campaign mixing the generator
 *     refuses to do. Section 3 of the provenance file prints what they would
 *     have won, so the cost of the exclusion is visible.
 *
 * LOOKUP COST
 *   n < 4096: one compare, one byte load from a 256-entry generated table
 *   (n >> 4), then an indirect tail call. That is the whole hot path. Above
 *   4096 the class walk runs at most five times, which is free at those sizes.
 *   No caching of a previous decision is needed or done: the table is already
 *   the cached decision, indexed by size, and adding state would make the rung
 *   non-reentrant.
 *
 * CALLING CONVENTION
 *   void *memcpy_hybrid(void *dst, const void *src, size_t n) — the same as
 *   every other rung, and it forwards its three arguments unchanged, so the
 *   tail call is a jump, not a frame. src and dst must not overlap, exactly as
 *   rungs 1-6. Nothing is written to the stack by this file.
 *
 * CORRECTNESS
 *   Whatever class n lands in, the callee is a rung that boots the same
 *   contract for every n (including n == 0 and unaligned src/dst), and every
 *   one of them already passes the harness's byte-for-byte + canary check. The
 *   same check on this rung therefore exercises every class: the harness walks
 *   n = 0..4096 with random offsets and then the standing size list, so the
 *   64 B / 3.4 ns winner, the 4 MiB winner and the clamps below 16 B are all
 *   verified, not assumed.
 */

#include "common.h"
#include "routing_table.h"

/* ------------------------------------------------------------------------- */
/* size class lookup — generated data, hand-written index                    */
/* ------------------------------------------------------------------------- */

/* Largest measured point that is <= n, clamped: n < 16 gives class 0, n above
 * 4 MiB gives the top class. Both directions are the Phase 2.5 rules. */
static inline unsigned routing_class(size_t n)
{
    if (n < 4096u)
        return (unsigned)routing_small[n >> 4];

    unsigned c = 7u;                     /* 4096 is class 7 */
    while (c + 1u < ROUTING_CLASSES && n >= routing_class_bytes[c + 1u])
        c++;
    return c;
}

/* ------------------------------------------------------------------------- */
/* the rung                                                                   */
/* ------------------------------------------------------------------------- */
void *memcpy_hybrid(void *dst, const void *src, size_t n)
{
    return ROUTING_TABLE[routing_class(n)](dst, src, n);
}

/* ------------------------------------------------------------------------- */
/* introspection used by tools/route_check.c (not on the hot path)            */
/* ------------------------------------------------------------------------- */

/* The class a size routes to. Exported so the boundary behaviour can be checked
 * exhaustively against the compiled object rather than inferred from source. */
unsigned memcpy_hybrid_class(size_t n)
{
    return routing_class(n);
}

/* The rung name for a size, from the same table the hot path indexes. */
const char *memcpy_hybrid_route_name(size_t n)
{
    return ROUTING_TABLE_NAMES[routing_class(n)];
}

/* Where the table came from. */
const char *memcpy_hybrid_provenance(void)
{
    return routing_provenance;
}

/* Number of classes, and their byte bounds, so a checker does not have to
 * duplicate the generator's list to walk it. */
unsigned memcpy_hybrid_classes(void)
{
    return (unsigned)ROUTING_CLASSES;
}

size_t memcpy_hybrid_class_bytes(unsigned c)
{
    return routing_class_bytes[c];
}
